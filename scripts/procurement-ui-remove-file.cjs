async (page) => {
  const count = (n) => page.getByText(`Проверьте распознанные строки · ${n}`, { exact: true }).waitFor()
  await count(4)
  const manual = await page.getByLabel('Описание 1', { exact: true }).inputValue()
  const upload = () => page.getByLabel('Файл заявки', { exact: true }).setInputFiles({ name: 'Тест.csv', mimeType: 'text/csv', buffer: Buffer.from('test') })
  await upload()
  await count(8)
  await page.getByRole('button', { name: 'Удалить позиции файла Тест.csv', exact: true }).click()
  await count(4)
  if (await page.getByLabel('Описание 1', { exact: true }).inputValue() !== manual) throw new Error('Manual rows lost')
  await page.getByLabel('Описание 1', { exact: true }).fill('Ручная строка после удаления')
  await page.getByRole('button', { name: 'Отменить удаление', exact: true }).click()
  await count(8)
  if (await page.getByLabel('Описание 1', { exact: true }).inputValue() !== 'Ручная строка после удаления') throw new Error('Undo overwrote remaining edits')
  await page.getByRole('button', { name: 'Удалить позиции файла Тест.csv', exact: true }).click()
  await count(4)
  await upload()
  await count(8)
  await page.getByRole('button', { name: 'Очистить список', exact: true }).click()
  await count(0)
  await upload()
  await count(4)
  await page.reload()
  await page.getByRole('button', { name: /^Новая заявка/ }).click()
  await count(4)
  await page.screenshot({ path: 'output/playwright/procurement-remove-file.png' })
  console.log('PASS: remove imported file only, preserve manual edits, undo, reload same file, clear all, persisted draft')
}
